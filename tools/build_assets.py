#!/usr/bin/env python3
"""Rebuild v69's published asset index and (optionally) shrink WebP artwork.

Run in repository: python tools/build_assets.py --optimize
Uses Pillow only for --optimize; index generation uses the Python stdlib.
Add new media to docs/ first, then rerun this tool before committing.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs'
MEDIA_EXT = {'.webp', '.png', '.jpg', '.jpeg', '.gif', '.svg', '.m4a', '.mp3', '.ogg', '.webm', '.wav', '.opus'}
PRESETS = {
    'icon01.webp': (320, 45_000, 78),
    'icon02.webp': (320, 45_000, 78),
    'icon03.webp': (320, 45_000, 78),
}

def optimize():
    try: from PIL import Image
    except ImportError as exc: raise SystemExit('Install Pillow once: py -m pip install Pillow') from exc
    savings = []
    for path in DOCS.rglob('*.webp'):
        rel = path.relative_to(DOCS).as_posix()
        if rel in PRESETS:
            max_width, max_size, quality = PRESETS[rel]
        elif rel.startswith('assets/characters/'):
            max_width, max_size, quality = 768, 155_000, 79
        elif rel.startswith('assets/card_themes/'):
            max_width, max_size, quality = 900, 70_000, 80
        elif path.name.startswith('stage') and '_bg.' in path.name or (path.name.startswith('intro_') and '_bg.' in path.name):
            max_width, max_size, quality = 1280, 250_000, 80
        elif path.name.startswith('stage') and '_boss' in path.name or path.name.startswith(('practice_boss','challenge_boss')):
            max_width, max_size, quality = 768, 155_000, 80
        else:
            continue  # Other artwork should be inspected before changing dimensions
        before=path.stat().st_size
        with Image.open(path) as original:
            if original.width <= max_width and before <= max_size:
                continue  # avoid repeated lossy transcoding
            img=original.copy()
            if img.width>max_width:
                scale=max_width/img.width
                img=img.resize((max_width, max(1,round(img.height*scale))),Image.Resampling.LANCZOS)
            from io import BytesIO
            buf=BytesIO()
            img.save(buf,format='WEBP',quality=quality,method=6)
            data=buf.getvalue()
            if len(data)<before:
                path.write_bytes(data)
                savings.append((rel,before,len(data)))
    return savings

def generate():
    paths=sorted(p for p in DOCS.rglob('*') if p.is_file() and p.suffix.lower() in MEDIA_EXT)
    record={p.relative_to(DOCS).as_posix():{'hash':hashlib.sha256(p.read_bytes()).hexdigest()[:12], 'bytes':p.stat().st_size} for p in paths}
    data='/* Auto-generated by tools/build_assets.py. Rebuild after adding/replacing assets. */\n'
    data+='window.RPG_ASSET_MANIFEST = Object.freeze('+json.dumps(record,ensure_ascii=False,sort_keys=True,separators=(',',':'))+');\n'
    (DOCS/'asset-manifest.js').write_text(data,encoding='utf-8')
    required=[]
    for i in range(1,6):
        required.extend([f'stage{i}_bg.webp',f'stage{i}_boss.webp',f'stage{i}_boss2.webp',f'stage{i}_bgm.m4a'])
    required.extend(['intro_locked_bg.webp','intro_unlocked_bg.webp','intro_master_bg.webp','intro_locked_bgm.m4a','intro_unlocked_bgm.m4a','intro_master_bgm.m4a'])
    available=set(record)
    # These are deliberately optional drop-in assets, not missing required dependencies.
    report={
      'media_count':len(paths),
      'media_bytes':sum(r['bytes'] for r in record.values()),
      'media_files':record,
      'optional_drop_in_assets_not_bundled':[x for x in required if x not in available],
      'note':'Unbundled optional media are omitted from requests and show the existing fallback. Rebuild this manifest when adding them.'
    }
    (ROOT/'ASSET_REPORT_v69.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return report

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--optimize',action='store_true',help='Resize/reencode oversized built-in WebP portraits/icons')
    args=p.parse_args()
    shrink=optimize() if args.optimize else []
    r=generate()
    print(f'{r["media_count"]} media files; {r["media_bytes"]:,} total bytes')
    for name,old,new in shrink:print(f'  {name}: {old:,} -> {new:,} ({(old-new)/old:.0%} smaller)')
    print(f'{len(r["optional_drop_in_assets_not_bundled"])} optional stage/intro media paths absent (skipped at runtime).')
