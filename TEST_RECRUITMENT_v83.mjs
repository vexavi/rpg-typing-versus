import assert from 'node:assert/strict';
import fs from 'node:fs';
import {makePull,chanceSix,getJstDate,RATES} from './docs/recruitment-core.mjs';
const catalog=JSON.parse(fs.readFileSync('./docs/gacha_catalog.json','utf8')).characters;
let checks=0;
const check=(c,m)=>{assert.ok(c,m);checks++};
check(catalog.length===14,'operator count');
check(catalog.filter(x=>x.rarity===4).length===8,'4-star count');
check(catalog.filter(x=>x.rarity===5).length===3,'5-star count');
check(catalog.filter(x=>x.rarity===6).length===3,'6-star count');
check(RATES.four+RATES.five+RATES.six===1,'base rates sum 1');
check(chanceSix(64)===.008,'pre-soft pity');
check(Math.abs(chanceSix(65)-.058)<1e-12,'soft pity at 66');
check(chanceSix(79)===1,'hard pity at 80');
check(getJstDate(new Date('2026-11-17T15:01:00Z'))==='2026-11-18','JST midnight');
const input={count:10,catalog,featuredId:'tavi'};
const n=makePull({...input,rng:()=>0.99});
check(n.results.length===10,'10 rewards');
check(n.results.every(x=>[4,5,6].includes(x.rarity)),'valid rarity');
check(n.results.some(x=>x.rarity>=5),'5-star guarantee');
check(n.pityFive<=9,'pity five safe');
check(n.pitySix===10,'pity six increment');
const six=makePull({count:1,catalog,featuredId:'tavi',pitySix:79,rng:()=>0.99});
check(six.results[0].rarity===6,'hard pity roll');
check(six.pitySix===0,'6-star pity reset');
check(six.featuredGuarantee,'losing 50/50 produces guarantee');
const guarantee=makePull({count:1,catalog,featuredId:'tavi',pitySix:79,featuredGuarantee:true,rng:()=>0.99});
check(guarantee.results[0].id==='tavi','featured guarantee');
check(guarantee.featuredGuarantee===false,'featured guarantee consumed');
const duplicate=makePull({count:1,catalog,owned:{vex:1},rng:()=>0.99});
check(duplicate.results[0].duplicate,'duplicate detected');
check(duplicate.shardsEarned===1,'4-star shard reward');
const rows=Array.from({length:100000},(_,i)=>makePull({count:1,catalog,rng:()=>Math.random()}).results[0].rarity);
let p6=rows.filter(x=>x===6).length/rows.length,p5=rows.filter(x=>x===5).length/rows.length;
check(p6>.006&&p6<.010,'base 6-star rate');
check(p5>.074&&p5<.086,'base 5-star rate');
console.log(`PASS: ${checks} core assertions; observed base 6★ ${String((p6*100).toFixed(2))}%, 5★ ${(p5*100).toFixed(2)}%.`);
